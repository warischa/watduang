// The PRE-PICK board chrome. lib.mjs (gh#303, read-only) stamps PICKED / COPY APPROVED and hardcodes the
// gh#303 generator path and the 2026-11-11 approval: those are post-pick functions, and these boards AWAIT the
// owner. This module replaces only that chrome (SRC, tag, copyRow, rulesRow, boardDoc); every helper that does
// not change (header, ORDER_LINE, the tables, nameFitRow, notesRow, FONTS, ANNOT_CSS, FIT_SCRIPT, the copy
// registry) is imported read-only from lib.mjs. New module, not a copy of lib.mjs: the fixture, th/nm, the fit
// script and the colour maths stay in gh#303's lib.mjs untouched.
import { header, ORDER_LINE, valuesTable, contrastTable, beatTable, nameFitRow, notesRow, FONTS, ANNOT_CSS, FIT_SCRIPT, reg, esc, CAP_NAME } from '../gh303-boards-2026-11-11/lib.mjs';

export { header, ORDER_LINE, valuesTable, contrastTable, beatTable, nameFitRow, notesRow, FONTS, ANNOT_CSS, FIT_SCRIPT };

// Where each Thai string on these boards comes from. 'new' is PROPOSED (awaiting the owner), never approved.
export const SRC = {
  new: 'PROPOSED on this board 2026-11-16 · awaiting the owner pick (not approved)',
  g302: 'gh#302 picked board copy (B NIGHT STAGE, approved 2026-11-11) · verbatim',
  g303: 'gh#303 picked board copy (approved 2026-11-11; L2 no-prize ruling, the final label) · verbatim',
  sample: 'sample data · not copy (stands in for what an MC or a player types)',
  ticket: 'gh#299 / gh#317 / gh#318 body · owner wording, verbatim (the game names)',
};

// An option tag: no PICKED stamp (nothing is picked yet), and COPY PROPOSED, not COPY APPROVED.
export const tag = (opt, label, text) => `<div class="tag"><span class="d">${opt} · ${label}</span>${text}<span class="pc">COPY PROPOSED</span></div>`;
export const sharedTag = (label, text) => `<div class="tag"><span class="d">${label}</span>${text}<span class="pc">COPY PROPOSED</span></div>`;

export function copyRow() {
  const rows = [...reg.REG.entries()].map(([text, { role, src }]) => `<tr><td>${esc(role)}</td><td class="thc">${esc(text)}</td><td>${esc(SRC[src] ?? src)}</td></tr>`).join('');
  const names = [...reg.NAMES];
  const sample = names.length ? `<tr><td>sample names (${names.length})</td><td class="thc">${names.slice(0, 8).map(esc).join(' · ')} …</td><td>${esc(SRC.sample)}; the gh#302 roster, one name at the 12-cluster limit (${esc(CAP_NAME)}), plus the NAME FIT worst cases</td></tr>` : '';
  return `
  <div class="brow">
    <h2>COPY SOURCES · every Thai string on this board, and where it comes from</h2>
    <p class="why">Strings in a frame: ${reg.REG.size} distinct${names.length ? `, plus ${names.length} distinct sample names` : ''}. New strings are <b>PROPOSED</b>, awaiting the owner pick; the gh#302 / gh#303 picked copy is reused verbatim and marked. None of the words gh#299 bars appears (the board's Thai scan checks it, raw and rendered).</p>
    <table class="tbl"><tr><th>role</th><th>string</th><th>source</th></tr>${rows}${sample}</table>
  </div>`;
}

export function rulesRow(queries, items) {
  return `
  <div class="brow">
    <h2>RULES CHECKED · ui-ux-pro-max 2.5.0 (design input, gh#299 owner ruling 2026-11-11)</h2>
    <p class="why">Queried 2026-11-16, one intent per query, rules taken and never its palette or fonts; no --persist, no --design-system. ${queries}</p>
    <div class="pin"><ul>${items.map((i) => `<li>${i}</li>`).join('')}</ul></div>
  </div>`;
}

export function boardDoc(title, comment, headLines, frameCss, rows, { width = 1520, extraHelmet = '', status = 'AWAITING OWNER', pick = '' } = {}) {
  return `<!doctype html>
<html lang="th">
<head>
  <meta charset="utf-8">
  <script src="./support.js"></script>
</head>
<body>
<x-dc>
<helmet>
  <style>
    /* Self-hosted faces, relative paths, the same files src/styles/fonts.css declares (Sarabun 400/700, Mitr 500/600/700).
       The board is design source and is never referenced at runtime. */${FONTS}

    /* ${comment} Generated by docs/verification/evidence/gh317-318-boards-2026-11-16/make-boards.mjs;
       edit the generator, not this file. Annotations are English and monospace. Every Thai string in a frame is PROPOSED COPY
       unless COPY SOURCES marks it verbatim (gh#302 / gh#303 picked, or the ticket's own wording). Frame values are literals
       (VALUES row: token, gh#302 / gh#303 pick, or PROPOSAL). The libs are imported read-only from gh303 at commit 1f57574. */${ANNOT_CSS}
${frameCss}${extraHelmet}
  </style>
</helmet>

<div data-pick="${pick}" style="width: ${width}px; background: #ffffff; color: #14142b;">
${header(title, headLines, status)}
${rows.join('\n')}
</div>
</x-dc>
${FIT_SCRIPT}
</body>
</html>
`;
}

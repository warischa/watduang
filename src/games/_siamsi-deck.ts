// The "เซียมซี" slip deck — gh#98. Data only, no DOM, so the distribution seam is testable on its own
// (see _siamsi-deck.test.mjs). The underscore prefix keeps this file out of the game page's lazy
// loader glob (`!../../games/_*.ts`), the same way _arm-gate.ts and _el.ts stay out: this is not a
// game module and must never be mounted as one.
//
// ADR-0011 gate. This deck is fortune text written ABOUT the reader, which is the risk class the ADR
// unlocked for the two fortune rows — not the dare library it refused. Its advice-register rule is
// the operative test and it is applied here: no item names a concrete medical, financial or legal
// act. Generic horoscope urging (patience, rest, speaking up, holding your tongue) is admitted by
// that rule explicitly. The ticket adds three of its own carve-outs, and they are enforced as a
// machine check in the test file: no legal outcome, no medical outcome, no digit anywhere in a text
// field (a number on a fortune slip reads as a lottery pick).
//
// The token scan in the test is a HEURISTIC and earns no coverage beyond the tokens it lists.
// ADR-0011 keeps "every item read by a human" universal, and that read is the real gate.
//
// Design source: design/SiamsiSlip.dc.html (ADR-0033). Slip fourteen is the canvas's own painted
// slip, carried over byte-for-byte rather than re-written — its grade, its four-line "กลอน", its four
// readings and its closing line are all the canvas value.

/** The four grades a slip may carry. The lowest is a warning, never a verdict about a life — which
 *  is why it is "ระวัง" and deliberately not the word for bad. */
export type Grade = 'ดีมาก' | 'ดี' | 'พอใช้' | 'ระวัง';

/** The four reading rows, in the fixed order they print in when the reader picked no subject. */
export type Aspect = 'work' | 'money' | 'love' | 'health';

/** What the reader may set their mind on at "ตั้งจิต". "any" is a real answer, not a skip: it means no
 *  row is promoted and the slip prints in its fixed order. */
export type Intent = Aspect | 'any';

export const ASPECT_ORDER: readonly Aspect[] = ['work', 'money', 'love', 'health'];

/** Thai labels for the reading rows and the intent chips. "คดีความ" and "คนเจ็บไข้" are deliberately
 *  absent: predicting a legal or a medical outcome is the riskiest content on this site. */
